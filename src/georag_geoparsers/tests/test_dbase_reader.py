"""Regression guard for the MapInfo binary-in-character decode.

Every number in this file was measured by hand against the RedStar delivery on
2026-08-24, not generated by the code under test. That matters more here than
in most parsers: the failure this module exists to prevent is silent. GDAL does
not error on these tables, it returns them 91.9% null, and a decode rule that
drifted would go on returning plausible-looking floats. The pinned values are
the only thing that would notice.

The four target files were chosen to cover the two ways the naive
"non-printable means binary" test fails, plus the two ways it must not fire:

* Sitka_trD.DAT       — binary doubles AND a width-4 binary int32
* soils                — the printable-bytes trap (cu_ppm) and the
                         trailing-NUL trap (samsubtype) in one table
* MiscPoints_2005.dbf  — ordinary ASCII dBASE, the no-regression guard
* alteration_riehle.dbf — ASCII dBASE with real decimals
"""

