def test_sitka_all_empty_columns_are_reported_as_text(sitka: DbaseTable) -> None:
    """Dip_DB and MidZ_DB are eight NUL bytes in all ten rows.

    Eight NULs is simultaneously a valid empty string and a valid 0.0, so a
    column made entirely of them carries no evidence either way and the module
    declines to guess — the documented "all-empty field reports text" rule.

    The bytes themselves are pinned below so the underlying fact survives even
    if that policy is ever revisited: the source data really is all-zero, and
    a caller that wants these as numeric zeros is making a semantic choice
    this reader deliberately does not make for it.
    """
    for name in ("Dip_DB", "MidZ_DB"):
        assert _field(sitka, name).decoded_as == "text"
        assert set(_column(sitka, name)) == {""}

    raw = SITKA_TRENCH.read_bytes()
    _count, header_len, record_len = struct.unpack("<IHH", raw[4:12])
    offsets: dict[str, int] = {}
    cursor = 1                                  # byte 0 of a record is the deletion flag
    for field in sitka.fields:
        offsets[field.name] = cursor
        cursor += field.length

    for name in ("Dip_DB", "MidZ_DB"):
        start = offsets[name]
        for row in range(10):
            cell = raw[header_len + row * record_len + start:][:8]
            assert cell == b"\x00" * 8
            assert struct.unpack("<d", cell)[0] == 0.0


