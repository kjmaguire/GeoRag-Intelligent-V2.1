#: Transcribed from tr006.4-geology_gcp.TAB, which MapInfo Discover wrote for
#: this exact table type. tr002.3-geology_gcp.DAT is the same table with its
#: .TAB missing, so its header declares all ten columns as 'C' and the reader
#: has to rediscover this list from the bytes alone.
GCP_DECLARED_TYPES = {
    "ID": "int32",
    "Use": "int32",           # 'Use Logical' — exposed as 0/1, see module docstring
    "Image_X": "int32",
    "Image_Y": "int32",
    "Map_X": "double",
    "Map_Y": "double",
    "RMS": "double",
    "ResidualX": "double",
    "ResidualY": "double",
    "Descriptio": "text",     # 'Description Char (100)', truncated to the 10-char DBF limit
}

GCP_DAT = REDSTAR / "Apollo Sitka" / "Trench" / "TR002" / "TR002.3" / "tr002.3-geology_gcp.DAT"
GCP_TAB = REDSTAR / "Apollo Sitka" / "Trench" / "TR006" / "tr006.4-geology_gcp.TAB"


def test_gcp_sidecar_still_declares_the_schema_this_test_was_written_against() -> None:
    """Guard the oracle itself — the test below is worthless if the .TAB moved."""
    declaration = GCP_TAB.read_text(encoding="latin-1")
    assert "Use Logical ;" in declaration
    assert "Map_X Float ;" in declaration
    assert "Image_X Integer ;" in declaration


def test_blind_decode_reproduces_the_types_mapinfo_declared() -> None:
    """Ten of ten, on a table the decode rule was never tuned against.

    The .DAT's own header calls every one of these columns 'C'. Recovering
    MapInfo's intended schema from the bytes — and agreeing with the sidecar
    it wrote for the sibling table — is the strongest available evidence that
    the magnitude window is measuring something real rather than fitting the
    two files the rule was derived from.
    """
    table = read_dbase(GCP_DAT)
    assert {f.name for f in table.fields} == set(GCP_DECLARED_TYPES)
    assert {f.dbase_type for f in table.fields} == {"C", "L"}   # the header's own claim

    recovered = {f.name: f.decoded_as for f in table.fields}
    assert recovered == GCP_DECLARED_TYPES


def test_gcp_values() -> None:
    table = read_dbase(GCP_DAT)
    assert len(table.rows) == 3
    assert _column(table, "ID") == [1, 2, 3]
    assert _column(table, "Image_X") == [1185, 1582, 2096]
    assert _column(table, "Descriptio") == ["Point 1", "Point 2", "Point 3"]
    # Map_X/Map_Y are UTM zone 4N metres and must land on the same trench as
    # the Sitka_trD midpoints, which were decoded from a different file.
    assert min(_column(table, "Map_X")) >= 400586
    assert max(_column(table, "Map_X")) <= 400864
    assert all(abs(v) < 10 for v in _column(table, "RMS"))


def test_logical_column_decodes_true_as_one() -> None:
    """MapInfo writes 0x01, not 'T'."""
    table = read_dbase(GCP_DAT)
    use = _field(table, "Use")
    assert use.dbase_type == "L"
    assert use.length == 1
    assert _column(table, "Use") == [1, 1, 1]

    raw = GCP_DAT.read_bytes()
    _count, header_len, record_len = struct.unpack("<IHH", raw[4:12])
    assert raw[header_len + 1 + 4] == 0x01      # deletion flag + ID(4), then Use


def _gcp_with_use_byte(tmp_path: Path, value: int) -> Path:
    """The real file with only the first record's Use byte changed."""
    raw = bytearray(GCP_DAT.read_bytes())
    _count, header_len, record_len = struct.unpack("<IHH", bytes(raw[4:12]))
    raw[header_len + 1 + 4] = value
    target = tmp_path / f"gcp_use_{value:02x}.DAT"
    target.write_bytes(bytes(raw))
    return target


def test_logical_false_is_zero_not_missing(tmp_path: Path) -> None:
    """0x00 means false here, and must not be swallowed as padding.

    This is the distinction the module's `_LOGICAL_FALSE` / `_LOGICAL_UNKNOWN`
    split exists for: a NUL is padding everywhere else in a dBASE record, but
    in a MapInfo logical cell it is a recorded answer.
    """
    table = read_dbase(_gcp_with_use_byte(tmp_path, 0x00))
    assert _field(table, "Use").decoded_as == "int32"
    assert _column(table, "Use") == [0, 1, 1]


def test_logical_unknown_is_none(tmp_path: Path) -> None:
    table = read_dbase(_gcp_with_use_byte(tmp_path, 0x20))
    assert _column(table, "Use") == [None, 1, 1]

    ascii_form = read_dbase(_gcp_with_use_byte(tmp_path, ord("F")))
    assert _column(ascii_form, "Use") == [0, 1, 1]


def test_undefined_logical_byte_demotes_the_column_to_text(tmp_path: Path) -> None:
    """An unrecognised flag costs the column its type, never its content."""
    table = read_dbase(_gcp_with_use_byte(tmp_path, ord("Z")))
    assert _field(table, "Use").decoded_as == "text"
    assert _column(table, "Use")[0] == "Z"


