def test_decoded_as_predicts_the_python_type(sitka: DbaseTable, soils: DbaseTable) -> None:
    """The closed vocabulary is a contract: text->str, double->float, int32->int.

    A caller builds column types from `fields` without sampling `rows`, so a
    label that did not predict the value type would be worse than no label.
    """
    expected = {"text": str, "double": float, "int32": int}
    for table in (sitka, soils):
        for field in table.fields:
            for row in table.rows:
                value = row[field.name]
                if value is None:
                    continue
                assert isinstance(value, expected[field.decoded_as]), (
                    f"{field.name} is labelled {field.decoded_as} but holds {type(value).__name__}"
                )
